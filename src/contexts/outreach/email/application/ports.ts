/** Everything the engine needs to render and send one claimed step. */
export interface SendClaim {
  sendId: string;
  organizationId: string;
  attempt: number;
  stepNumber: number;
  enrollmentId: string;
  campaignId: string;
  mailbox: { id: string; emailAddress: string; displayName: string | null; signatureHtml: string | null };
  person: { id: string; email: string; variables: Record<string, string | null> };
  step: { subject: string; body: string; waitDays: number };
  /** The step after this one, if any, for scheduling the follow-up. */
  nextStep: { waitDays: number } | null;
  /** Earlier sends of this enrollment. Message-ID and thread id are blank for sends from another mailbox, which cannot be threaded onto. */
  priorSent: PriorSend[];
  /** The mailbox that sent the earlier steps, when this mailbox took the follow-up over from it. Null for ordinary sends. */
  takenOverFrom: string | null;
}

/** `enrollment_stopped`: the enrollment is no longer pending or active (replied, bounced, suppressed, cancelled). */
export type BlockReason = "campaign_inactive" | "suppressed" | "do_not_contact" | "enrollment_stopped";

export interface ClaimOptions {
  mailboxId: string;
  now: Date;
  /** Chooses the gap to place after this claim from the organization's stored email rules. The caller owns randomness, so tests control it. */
  pickGapMinutes: (storedEmailRules: Record<string, unknown> | null) => number;
  /** Hours a pinned mailbox may stay unable to send before this mailbox may claim its due follow-ups, from the stored email rules. */
  takeoverAfterHours: (storedEmailRules: Record<string, unknown> | null) => number;
  /** Fallback zone when the mailbox sets none. */
  defaultWorkingHours: (organizationTimeZone: string | null) => WorkingHours;
  /** Defensive re-check of MAILBOX_ALLOWED_DOMAINS at claim time. Omitted means no check. */
  domainPolicy?: MailboxDomainPolicy;
}

/** Port for outreach persistence. Each method is one atomic step. */
export interface OutreachStore {
  /**
   * Connected mailboxes due to send, oldest claim first, so none starves. A mailbox whose address domain the policy
   * refuses is left out and counted in `blockedByDomainPolicy` (every connected mailbox counts, due or not).
   */
  listSendableMailboxIds(now: Date, policy: MailboxDomainPolicy): Promise<{ ids: string[]; blockedByDomainPolicy: number }>;
  /**
   * In one transaction: lock the mailbox, check hours, gap and daily limit,
   * pick the next due enrollment, record the claim (a `sends` row) and place
   * the gap. Returns null when the mailbox may not send or nothing is due.
   */
  claimNext(options: ClaimOptions): Promise<SendClaim | null>;
  /** Re-checks the enrollment status, the campaign, the suppression list and do-not-contact right before the provider call. */
  checkBlockers(claim: SendClaim): Promise<BlockReason | null>;
  /** Records the blocker, ends the enrollment and releases the claim without a retry. */
  abandon(claim: SendClaim, reason: BlockReason, now: Date): Promise<void>;
  /** Stores the rendered message on the claim so a crash after this point can be reconciled. */
  recordRendered(claim: SendClaim, rendered: { subject: string; body: string; rfcMessageId: string }): Promise<void>;
  markSent(claim: SendClaim, sent: SentEmail, now: Date): Promise<void>;
  /** The provider refused; schedule a retry or give up after the last attempt. */
  markFailed(claim: SendClaim, error: string, now: Date, retryAfterMinutes: number, maxAttempts: number): Promise<void>;
  markUnknown(claim: SendClaim, error: string): Promise<void>;
  /** Sends that are uncertain, or were claimed and never finished. */
  listUncertain(olderThan: Date, limit: number): Promise<UncertainSend[]>;
  resolveUncertainAsSent(send: UncertainSend, sent: SentEmail, now: Date): Promise<void>;
  /** Not in the mailbox after the grace period: make the step retryable. */
  resolveUncertainAsNotSent(send: UncertainSend, now: Date, retryAfterMinutes: number, maxAttempts: number, cause: NotSentCause): Promise<void>;
}

export interface UncertainSend {
  sendId: string;
  organizationId: string;
  enrollmentId: string;
  stepNumber: number;
  attempt: number;
  claimedAt: Date;
  rfcMessageId: string | null;
  mailboxEmail: string;
  /** The lead's address, passed to `findSent` as the recipient hint. */
  recipientEmail: string | null;
  /** Wait of the step after this one, for scheduling when the send turns out to have gone out. */
  nextStepWaitDays: number | null;
}
