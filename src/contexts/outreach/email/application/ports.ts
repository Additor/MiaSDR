/** Outcome classes a provider adapter must report. The engine never guesses. */
export class ProviderSendError extends Error {
  constructor(
    message: string,
    /**
     * definite: the provider refused and nothing was sent (auth, bad address). Safe to retry later.
     * unknown: timeout or dropped connection; the message may have been accepted. Never retried blindly.
     */
    readonly kind: "definite" | "unknown",
  ) {
    super(message);
  }
}

export interface OutgoingEmail {
  mailbox: { emailAddress: string; displayName: string | null };
  to: string;
  /** Visible copy recipients a person chose for a reply. Campaign mail never sets this. */
  cc?: string[];
  subject: string;
  bodyText: string;
  bodyHtml: string;
  /** Generated by us before sending, so an uncertain send can be found in the mailbox afterwards. */
  rfcMessageId: string;
  inReplyTo: string | null;
  references: string[];
  threadId: string | null;
  /** The HTTPS endpoint a mail client POSTs to (RFC 8058), not the confirmation page. */
  listUnsubscribeUrl: string;
}

export interface SentEmail {
  providerMessageId: string;
  threadId: string | null;
}

export interface InboundEmail {
  providerMessageId: string;
  threadId: string | null;
  rfcMessageId: string | null;
  inReplyTo: string | null;
  references: string[];
  from: { email: string; name: string | null };
  to: string[];
  /** Cc and Resent-Cc addresses, lowercased and deduplicated. Not filtered against the lead or our mailbox. */
  cc: string[];
  subject: string;
  bodyText: string;
  receivedAt: Date;
  /** Lowercased names of the headers bounce detection and auto-reply checks read (content-type, auto-submitted, x-failed-recipients, and similar). Gmail also records the raw `authentication-results` (first value, at most 2000 characters) and `received-spf` headers. */
  headers: Record<string, string>;
  /** Our `X-MiaSDR-Send-Id`, present when this message quotes or replies to one of ours and the provider kept it. */
  sendId: string | null;
}

export interface InboundBatch {
  messages: InboundEmail[];
  /** Store this only after every message in the batch was handled. */
  cursor: string;
}

export type FindSentResult =
  | { status: "found"; sent: SentEmail }
  | { status: "absent" }
  | { status: "inconclusive"; reason: string };

/** Optional narrowing for `findSent`. `to` is the recipient address; adapters use it to shrink the scan. */
export interface FindSentHint {
  to?: string;
}

/** Port for a connected mailbox: Gmail via service account today, per-user OAuth later. */
export interface MailboxProvider {
  /** Confirms we can act as this mailbox. Throws with a reason a person can act on. */
  verify(emailAddress: string): Promise<void>;
  send(email: OutgoingEmail): Promise<SentEmail>;
  /**
   * Looks for a message we sent, by the id we set. `since` is when the send was claimed; the search must
   * cover everything from then on. `absent` is proof of absence and is returned only after an exhaustive
   * scan of that window. Anything less (page cap, window beyond the adapter's horizon) is `inconclusive`.
   * An API failure throws. Callers must never treat `inconclusive` or a throw as "not sent".
   * Pass `hint.to` (the recipient) whenever known: it makes the scan cheap on busy mailboxes. An adapter
   * may also answer `inconclusive` for a claim too young for its index to be trusted.
   */
  findSent(mailbox: { emailAddress: string }, rfcMessageId: string, since: Date, hint?: FindSentHint): Promise<FindSentResult>;
  /**
   * New inbox mail since `cursor`. A null cursor means first sync: return no messages and the
   * mailbox's current cursor, so history before the mailbox was connected is never ingested.
   * An expired cursor behaves like null and must be reported through `reset: true`.
   */
  fetchInbound(mailbox: { emailAddress: string }, cursor: string | null): Promise<InboundBatch & { reset?: boolean }>;
  /**
   * Fetches specific messages by provider id, for retrying a message the cursor already moved past.
   * Ids the mailbox no longer holds (deleted, or a sent message or draft) come back in `missing`.
   */
  fetchMessages(mailbox: { emailAddress: string }, providerMessageIds: string[]): Promise<{ messages: InboundEmail[]; missing: string[] }>;
}

